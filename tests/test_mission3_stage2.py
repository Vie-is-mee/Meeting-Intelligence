ROOT=Path(__file__).resolve().parents[1]

class FrozenClient:
    def __init__(self,events):
        self.events=events
    def completion_json(self,system,user):
        if '"events"' in system:
            return {"events":self.events}
        return {"findings":[]}

def event(kind,typ,sid,value,topic="test",key="test",**kwargs):
    return Event(issue_key=key,topic=topic,kind=kind,event_type=typ,
                 source_ids=[sid],value=value,**kwargs)


class Stage2MissingInformationTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        d=json.loads((ROOT/"docs/evaluation/final_regression_round5_retry2.json").read_text(encoding="utf-8"))
        cls.archive={c["id"]:c for c in d["cases"]}
        inp=json.loads((ROOT/"docs/evaluation/final_regression_input_v2.json").read_text(encoding="utf-8"))
        cls.inputs={c["id"]:c["transcript"] for c in inp["cases"]}

    def run_archived(self,cid):
        old=self.archive[cid]["output"]
        seen=set()
        hypotheses=[]
        for r in old["records"]:
            for e in r["history"]:
                token=json.dumps(e,ensure_ascii=False,sort_keys=True)
                if token not in seen:
                    hypotheses.append(e)
                    seen.add(token)
        result=analyze(self.inputs[cid],client=FrozenClient(hypotheses),audit=False)
        return result

    def test_H03_request_and_unaccepted_relative_bound_recovered(self):
        result=self.run_archived("H03")
        requests=[r for r in result.records if r.kind=="request"]
        self.assertEqual(len(requests),1)
        r=requests[0]
        self.assertEqual(r.meeting_status,"recorded")
        self.assertEqual(r.due_raw,"trước lần thử tiếp theo")
        self.assertIsNone(r.owner)
        self.assertEqual(r.field_evidence_ids["due_raw"],["L001"])
        self.assertEqual(r.review_status,"needs_review")
        self.assertTrue(any("khôi phục" in w.lower() or "Bổ sung" in w for w in result.warnings))
        self.assertTrue(any(x.kind=="decision" and x.meeting_status=="open" for x in result.records))

    def test_LC02_explicit_alternative_choice_open_not_approved(self):
        result=self.run_archived("LC02")
        opened=[r for r in result.records if r.kind=="decision" and r.meeting_status=="open"]
        self.assertEqual(len(opened),1)
        r=opened[0]
        self.assertIn("cách triển khai thay thế",r.content.lower())
        self.assertIn("L005",r.evidence_ids)
        self.assertEqual(r.review_status,"needs_review")
        self.assertTrue(any(x.kind=="request" and x.meeting_status=="recorded" for x in result.records))
        self.assertTrue(any(x.kind=="action" and x.meeting_status=="cancelled" for x in result.records))
        self.assertFalse(any(x.kind=="action" and x.meeting_status=="assigned" for x in result.records))

    def test_old_four_pass_cases_do_not_get_spurious_recoveries(self):
        for cid in ["D01","D03","D04","H01"]:
            with self.subTest(case=cid):
                result=self.run_archived(cid)
                prior=len(self.archive[cid]["output"]["records"])
                self.assertEqual(len(result.records),prior)
                self.assertFalse(any(r.issue_key.startswith("m3_recovered_") for r in result.records))

    def test_no_autogenerated_request_from_named_assignment(self):
        lines=parse_transcript("L001 | An | Cần Lan làm bảng báo cáo.")
        events,ids=recover_explicit_omissions([],lines,[])
        self.assertFalse(ids)
        self.assertEqual(events,[])

    def test_no_recovery_from_question_or_hypothetical(self):
        lines=parse_transcript("L001 | An | Cần làm gì đây?\n"
                               "L002 | Lan | Giả sử chưa chọn cách triển khai thì sao?\n"
                               "L003 | Minh | Đề xuất cần kiểm thử lại.")
        events,ids=recover_explicit_omissions([],lines,[])
        self.assertFalse(ids)
        self.assertFalse(events)

    def test_literal_request_without_action_generates_review_only(self):
        lines=parse_transcript("L001 | An | Cần kiểm tra chứng chỉ trước đợt thử thứ hai.")
        events,keys=recover_explicit_omissions([],lines,[])
        self.assertEqual(len(events),1)
        record=resolve_events(events,lines)[0]
        self.assertEqual(record.kind,"request")
        self.assertEqual(record.due_raw,"trước đợt thử thứ hai")
        self.assertEqual(keys,{"m3_recovered_request_L001"})

    def test_explicit_choice_without_prior_decision_is_review_only(self):
        lines=parse_transcript("L001 | Bình | Chưa chọn nhà cung cấp cho báo cáo.")
        events,keys=recover_explicit_omissions([],lines,[])
        self.assertEqual(len(events),1)
        self.assertEqual(events[0].event_type,"unresolved")
        self.assertEqual(keys,{"m3_recovered_open_L001"})

    def test_existing_open_choice_not_duplicated(self):
        lines=parse_transcript("L001 | Bình | Chưa chọn nhà cung cấp cho báo cáo.")
        prior=[event("decision","unresolved","L001","Chưa chọn nhà cung cấp",
                     topic="nhà cung cấp",key="vendor")]
        events,keys=recover_explicit_omissions(prior,lines,[])
        self.assertEqual(len(events),1)
        self.assertFalse(keys)

    def test_existing_agreed_choice_not_reopened_by_rule(self):
        lines=parse_transcript("L001 | Bình | Chốt nhà cung cấp A.\n"
                               "L002 | Lan | Chưa chọn nhà cung cấp B.")
        prior=[event("decision","agreement","L001","nhà cung cấp A",
                     topic="nhà cung cấp",key="vendor")]
        events,keys=recover_explicit_omissions(prior,lines,[])
        self.assertEqual(len(events),1)
        self.assertFalse(keys)

    def test_not_publishing_recovered_records_as_approved(self):
        result=self.run_archived("H03")
        recovered=[r for r in result.records if r.issue_key.startswith("m3_recovered_")]
        self.assertTrue(recovered)
        self.assertTrue(all(r.authority_status=="unknown" and r.review_status=="needs_review"
                            for r in recovered))


    def test_LC02_drops_task_echo_proposal_but_keeps_open_choice(self):
        result=self.run_archived("LC02")
        self.assertEqual(sorted((r.kind,r.meeting_status) for r in result.records),
                         [("action","cancelled"),("decision","open"),("request","recorded")])
        self.assertTrue(any("Loại proposal trùng" in w for w in result.warnings))

    def test_old_minutes_and_hypothetical_are_not_recovered(self):
        lines=parse_transcript("L001 | An | Chưa chọn nhà cung cấp, theo biên bản cũ.\n"
                               "L002 | Lan | Cần kiểm tra kế hoạch, chỉ là mẫu.")
        events,ids=recover_explicit_omissions([],lines,[])
        self.assertFalse(ids)
        self.assertEqual(events,[])

    def test_mixed_later_approval_in_one_utterance_does_not_autogenerate_open(self):
        lines=parse_transcript("L001 | Lan | Chưa chọn nhà cung cấp A, sau đó đã chọn nhà cung cấp B.")
        warnings=[]
        events,ids=recover_explicit_omissions([],lines,warnings)
        self.assertFalse(ids)
        self.assertEqual(events,[])
        self.assertTrue(warnings)

    def test_old_H03_two_false_deadline_findings_not_applied(self):
        old=self.archive["H03"]["output"]
        class Client:
            def __init__(self, events, findings):
                self.events=events
                self.findings=findings
                self.calls=0
            def completion_json(self,*args):
                self.calls+=1
                return {"events":self.events} if self.calls==1 else {"findings":self.findings}
        events=[e for rec in old["records"] for e in rec["history"]]
        result=analyze(self.inputs["H03"],client=Client(events,old["audit_findings"]),audit=True)
        self.assertEqual(result.audit_findings,[])
        self.assertEqual(len([r for r in result.records if r.kind=="request"]),1)

    def test_no_auto_assignment_from_unresolved_choice(self):
        lines=parse_transcript("L001 | Lan | Chưa chọn cách triển khai thay thế và chưa giao ai.")
        events,ids=recover_explicit_omissions([],lines,[])
        self.assertTrue(ids)
        self.assertEqual([e.kind for e in events],["decision"])


class Stage2FieldEvidenceTests(unittest.TestCase):
    def test_proposed_deadline_is_not_accepted_as_due(self):
        lines=parse_transcript("L001 | Lan | Tôi nhận kiểm thử.\n"
                               "L002 | Huy | Hay đặt hạn thứ Tư?")
        e=event("action","assignment","L001","kiểm thử",
                owner="Lan",due_raw="thứ Tư")
        # Explicitly bind claimed date to the actual question.
        r=resolve_events([e],lines)[0]
        r.field_evidence_ids["due_raw"]=["L002"]
        result=verify_records([r],lines)[0]
        self.assertIsNone(result.due_raw)
        self.assertEqual(result.review_status,"needs_review")

    def test_date_confirmed_by_same_evidence_is_preserved(self):
        lines=parse_transcript("L001 | Lan | Tôi nhận kiểm thử, hạn thứ Tư.")
        r=verify_records(resolve_events([event("action","assignment","L001","kiểm thử",
                               owner="Lan",due_raw="thứ Tư")],lines),lines)[0]
        self.assertEqual(r.due_raw,"thứ Tư")

    def test_unverified_agreement_not_upgraded_from_question(self):
        lines=parse_transcript("L001 | Lan | Hay chọn phương án B?")
        r=verify_records(resolve_events([event("decision","agreement","L001","phương án B",
                               topic="kho",key="kho")],lines),lines)[0]
        self.assertEqual(r.meeting_status,"unverified")
        self.assertEqual(r.review_status,"needs_review")

    def test_real_agreement_not_rejected(self):
        lines=parse_transcript("L001 | Lan | Thống nhất chọn phương án B.")
        r=verify_records(resolve_events([event("decision","agreement","L001","phương án B",
                               topic="kho",key="kho")],lines),lines)[0]
        self.assertEqual(r.meeting_status,"agreed")

    def test_owner_not_assigned_source_does_not_support_owner(self):
        lines=parse_transcript("L001 | Minh | Chưa giao việc kiểm thử cho Lan.")
        r=verify_records(resolve_events([event("action","assignment","L001","kiểm thử",
                                                owner="Lan")],lines),lines)[0]
        self.assertIsNone(r.owner)
        self.assertEqual(r.meeting_status,"unverified")
        self.assertEqual(r.review_status,"needs_review")

    def test_source_explicitly_not_selected_cannot_support_agreement(self):
        lines=parse_transcript("L001 | An | Chưa chốt phương án B.")
        r=verify_records(resolve_events([event("decision","agreement","L001","phương án B",
                               topic="kho",key="kho")],lines),lines)[0]
        self.assertEqual(r.meeting_status,"unverified")

    def test_condition_numeric_threshold_without_evidence_is_held(self):
        lines=parse_transcript("L001 | An | Chốt beta nếu kiểm thử đạt 500 người.")
        e=event("decision","conditional_agreement","L001","mở beta",
                topic="beta",key="beta",condition="kiểm thử đạt 300 người")
        r=verify_records(resolve_events([e],lines),lines)[0]
        self.assertEqual(r.meeting_status,"unverified")
        self.assertEqual(r.review_status,"needs_review")
        self.assertTrue(any("ngưỡng số" in x for x in r.warnings))

    def test_condition_verified_threshold_retained(self):
        lines=parse_transcript("L001 | An | Chốt beta nếu kiểm thử đạt 500 người.")
        e=event("decision","conditional_agreement","L001","mở beta",
                topic="beta",key="beta",condition="kiểm thử đạt 500 người")
        r=verify_records(resolve_events([e],lines),lines)[0]
        self.assertEqual(r.meeting_status,"conditional")

    def test_invalid_field_evidence_id_fail_closed(self):
        lines=parse_transcript("L001 | An | Chốt B.")
        r=resolve_events([event("decision","agreement","L001","B",topic="kho",key="kho")],lines)[0]
        r.field_evidence_ids["meeting_status"]=["L999"]
        result=verify_records([r],lines)[0]
        self.assertEqual(result.meeting_status,"unverified")
        self.assertTrue(any("không tồn tại" in x for x in result.warnings))

    def test_independent_proposal_not_suppressed_by_task(self):
        lines=parse_transcript("L001 | An | Tôi đề xuất dùng thư viện X.\n"
                               "L002 | Bình | Dũng thử thư viện X.\n"
                               "L003 | Dũng | Tôi nhận thử thư viện X.\n"
                               "L004 | Bình | Hủy việc thử thư viện X.")
        events=[
            event("decision","proposal","L001","dùng thư viện X",topic="phương án",key="decision_x"),
            event("action","assignment","L003","thử thư viện X",topic="thử",key="task_x",owner="Dũng"),
            event("action","action_cancelled","L004",None,topic="thử",key="task_x")
        ]
        result=verify_records(resolve_events(events,lines),lines)
        self.assertEqual({r.kind for r in result},{"action","decision"})

    def test_accepted_deadline_after_proposed_date_is_not_cleared(self):
        lines=parse_transcript("L001 | Lan | Tôi nhận kiểm thử.\n"
                               "L002 | Huy | Hay hạn thứ Tư?\n"
                               "L003 | Lan | Tôi xác nhận hạn thứ Tư.")
        e=event("action","assignment","L001","kiểm thử",owner="Lan",due_raw="thứ Tư")
        r=resolve_events([e],lines)[0]
        r.field_evidence_ids["due_raw"]=["L002","L003"]
        result=verify_records([r],lines)[0]
        self.assertEqual(result.due_raw,"thứ Tư")

    def test_genuine_accepted_deadline_finding_is_retained(self):
        from meeting_intelligence.auditor import audit_events
        lines=parse_transcript("L001 | Lan | Hay hạn thứ Tư?\n"
                               "L002 | An | Chốt hạn thứ Năm.")
        events=[event("decision","unresolved","L001","chưa chốt hạn",topic="hạn",key="deadline")]
        rows=resolve_events(events,lines)
        finding={"issue_key":"deadline","kind":"decision","category":"missing_late_change",
                 "severity":"high","source_ids":["L002"],"source_quote":"Chốt hạn thứ Năm.",
                 "explanation":"An accepted deadline on Thursday is missing"}
        class Client:
            def completion_json(self,*args):return {"findings":[finding]}
        accepted,ignored=audit_events(lines,events,rows,Client())
        self.assertEqual(len(accepted),1)
        self.assertEqual(ignored,[])

